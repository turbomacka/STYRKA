import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdirSync } from 'node:fs';
import { signUp, onboard, uniqueEmail } from './helpers';

test('A–J: plan, autosave, register, effort, persistent rest, swap, reduce, undo and finish',async({page,context},info)=>{
  test.setTimeout(150000);
  const dir=`docs/evidence/adaptive-2026-10-22/${info.project.name}`;mkdirSync(dir,{recursive:true});
  await page.emulateMedia({colorScheme:'light'});
  await signUp(page,uniqueEmail('workout-ux'));await onboard(page);
  await expect(page.getByRole('navigation',{name:'Huvudmeny'}).getByRole('link')).toHaveCount(3);
  await page.screenshot({path:`${dir}/plan-light.png`,fullPage:true});
  await page.getByRole('button',{name:'Öppna passet',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Ditt pass',exact:true})).toBeVisible();
  const firstCard=page.locator('.workout-card').first();await firstCard.locator('.workout-title').click();
  await firstCard.getByRole('button',{name:/Vikt set 1:/}).click();
  await firstCard.getByLabel('Vikt (kg)',{exact:true}).fill('82,5');
  await expect(firstCard.getByRole('status')).toContainText('Planen sparad');
  await expect(firstCard.locator('.set-row.done')).toHaveCount(0);
  await firstCard.getByRole('button',{name:'Stäng',exact:true}).click();
  await page.screenshot({path:`${dir}/overview-light.png`,fullPage:true});
  await page.reload();await page.locator('.workout-card').first().locator('.workout-title').click();
  await expect(page.locator('.workout-card').first().getByRole('button',{name:/Vikt set 1:/})).toContainText('82,5');
  await page.getByRole('button',{name:'Starta passet',exact:true}).click();
  const first=page.getByRole('listitem',{name:'Arbetsset 1',exact:true});
  await first.getByRole('button',{name:'Registrera set 1',exact:true}).click();
  await expect(first.getByRole('button',{name:'Set 1 utfört. Ändra eller ångra'})).toBeVisible();
  const timer=page.getByRole('region',{name:'Vilotimer'});await expect(timer).toBeVisible();
  const seconds=async()=>Number((await timer.getByRole('timer').getAttribute('aria-label'))!.split(' ')[0]);
  const before=await seconds();
  await first.getByRole('button',{name:'Tungt',exact:true}).click();
  await expect.poll(seconds).toBeGreaterThan(before+20);
  const beforeAdjustment=await seconds();
  await timer.getByRole('button',{name:'+30 s',exact:true}).click();
  await expect.poll(seconds).toBeGreaterThan(beforeAdjustment+20);
  const adjusted=await seconds();
  await page.evaluate(()=>window.scrollTo(0,0));
  await expect.poll(()=>page.locator('.train-head').evaluate(el=>Math.round(el.getBoundingClientRect().top))).toBe(0);
  await page.screenshot({path:`${dir}/training-viewport-light.png`});
  await page.screenshot({path:`${dir}/training-light.png`,fullPage:true});
  const offlineReload=info.project.name!=='iphone-webkit';
  if(offlineReload){await page.evaluate(async()=>{await navigator.serviceWorker.ready;});await context.setOffline(true);}
  else info.annotations.push({type:'limitation',description:'Windows WebKit: reload online; service worker offline requires physical iPhone QA.'});
  await page.reload();
  await expect(timer).toBeVisible();expect(await seconds()).toBeLessThanOrEqual(adjusted);expect(await seconds()).toBeGreaterThan(adjusted-20);
  await expect(first.getByRole('button',{name:/Vikt set 1:/})).toContainText('82,5');
  await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'});
  await page.screenshot({path:`${dir}/training-dark-${offlineReload?'offline':'online-reload'}.png`,fullPage:true});
  await page.evaluate(()=>document.documentElement.style.fontSize='200%');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth+1)).toBe(true);
  await page.evaluate(()=>document.documentElement.style.fontSize='');
  const a11y=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
  expect(a11y.violations.map((v)=>({id:v.id,nodes:v.nodes.map((n)=>n.target)}))).toEqual([]);
  await context.setOffline(false);
  await first.getByRole('button',{name:'Set 1 utfört. Ändra eller ångra'}).click();
  await first.getByRole('button',{name:'Ångra registrering'}).click();
  await expect(first.getByRole('button',{name:'Registrera set 1'})).toBeVisible();
  await first.getByRole('button',{name:'Registrera set 1'}).click();
  await page.getByRole('button',{name:'Byt övning',exact:true}).click();
  await page.getByRole('searchbox',{name:'Sök övning'}).fill('front');
  await page.getByRole('button',{name:'Frontböj',exact:true}).click();
  const familiar=page.getByRole('radio',{name:'Ja',exact:true});if(await familiar.isVisible())await familiar.click();
  await page.getByRole('button',{name:/Byt till frontböj/i}).click();
  await expect(page.locator('.train-head h1')).toHaveText('Frontböj');
  await page.getByRole('button',{name:'Nästa övning',exact:true}).click();
  await expect(page.locator('.train-head h1')).toHaveText('Bänkpress');
  await expect(timer).toHaveCount(0);
  const focused=await page.locator('.train-head h1').textContent();
  await page.getByRole('button',{name:'Hela passet'}).click();
  await page.getByRole('button',{name:'Fortsätt träna'}).click();
  await expect(page.locator('.train-head h1')).toHaveText(focused!);
  await page.getByRole('button',{name:'Hela passet'}).click();
  await expect(page.locator('.equipment-panel')).toHaveCount(0);
  const card=page.locator('.workout-card').first();await card.locator('.workout-title').click();
  await card.getByRole('button',{name:'Ta bort återstående',exact:true}).click();
  await page.locator('.toast').getByRole('button',{name:'Ångra',exact:true}).click();
  await expect(page.locator('.workout-card').first()).toContainText('Frontböj');
  await page.screenshot({path:`${dir}/overview-dark.png`,fullPage:true});
  await page.getByRole('button',{name:'Fortsätt träna'}).click();
  await page.getByRole('button',{name:'Avsluta',exact:true}).click();
  await page.getByRole('button',{name:'Avsluta och spara'}).click();
  await expect(page.getByRole('heading',{name:'Så påverkas nästa pass'})).toBeVisible();
  await page.screenshot({path:dir+'/replanning.png',fullPage:true});
  await page.getByRole('button',{name:'Till planen',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Min träningsplan'})).toBeVisible();
  await expect(page.getByText('Passet är sparat',{exact:true})).toBeVisible();
  await page.screenshot({path:`${dir}/finish-plan-dark.png`,fullPage:true});
  await page.getByRole('button',{name:'Visa genomfört pass'}).click();
  await expect(page.locator('.plan-row').first()).toContainText('set');
});
