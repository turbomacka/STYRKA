import AxeBuilder from '@axe-core/playwright';
import { expect, test } from '@playwright/test';
import { onboard, signUp, uniqueEmail } from './helpers';

test('orsak till överhopp, tydligt förslag, godkännande och ångra på mobil', async ({ page, context }, info) => {
  await signUp(page, uniqueEmail('skip'));
  await onboard(page);
  await page.getByRole('button', { name: 'Starta dagens pass' }).click();
  await page.getByRole('button', { name: 'Starta', exact: true }).click();
  await page.getByRole('button', { name: 'Klart, set 1' }).click();
  await page.getByRole('button', { name: 'Nästa övning', exact: true }).click();
  await page.getByRole('button', { name: 'Nästa övning', exact: true }).click();
  await page.getByRole('button', { name: 'Nästa övning', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sidolyft i kabel' })).toBeVisible();
  await page.getByRole('button', { name: 'Hoppa över övningen', exact: true }).click();
  await context.setOffline(true);
  await page.getByRole('button', { name: 'Hann inte', exact: true }).click();
  await expect(page.getByText(/Sidolyft i kabel – överhoppat: hann inte/)).toBeVisible();
  await page.getByRole('button', { name: 'Avsluta', exact: true }).click();
  await page.getByRole('button', { name: 'Spara passet', exact: true }).click();
  const proposal = page.getByRole('region', { name: 'Anpassning av nästa pass' });
  await expect(proposal.getByRole('heading', { name: 'Ett förslag efter förra passet' })).toBeVisible();
  await expect(proposal).toContainText('Sidolyft i kabel prioriteras');
  await expect(proposal).toContainText('utgår ur det här passet');
  await expect(proposal).toContainText('Planen ändras när du godkänner');
  const a11y = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  expect(a11y.violations.filter((v) => ['serious', 'critical'].includes(v.impact ?? ''))).toEqual([]);
  await page.screenshot({ path: `test-results/skip-${info.project.name}.png`, fullPage: true });
  await proposal.getByRole('button', { name: 'Använd förslaget nästa pass' }).click();
  await expect(proposal.getByRole('heading', { name: 'Ditt val för nästa pass' })).toBeVisible();
  await context.setOffline(false);
  await page.getByRole('button', { name: 'Till Idag', exact: true }).click();
  await expect(page.getByRole('list', { name: 'Övningar i passet' })).toContainText('Sidolyft i kabel');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Ditt val för nästa pass' })).toBeVisible();
  await page.getByRole('link', { name: 'Plan', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Anpassning av nästa pass' })).toContainText('Sidolyft i kabel');
  await page.getByRole('button', { name: 'Ångra ändringen' }).click();
  await page.getByRole('link', { name: 'Idag', exact: true }).click();
  await expect(page.getByRole('list', { name: 'Övningar i passet' })).not.toContainText('Sidolyft i kabel');
  const d = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, width: document.documentElement.clientWidth }));
  expect(d.scroll).toBeLessThanOrEqual(d.width + 1);
});
