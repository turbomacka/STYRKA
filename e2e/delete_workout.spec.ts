import AxeBuilder from '@axe-core/playwright';
import { expect, test } from '@playwright/test';
import { onboard, signUp, uniqueEmail } from './helpers';

test('radera registrerat pass: avbryt, bekräfta offline, historik och omladdning', async ({ page, context }) => {
  await signUp(page, uniqueEmail('delete'));
  await onboard(page);
  await page.getByRole('button', { name: 'Öppna passet' }).click();
  await page.getByRole('button', { name: 'Starta passet', exact: true }).click();
  await page.getByRole('button', { name: 'Registrera set 1' }).click();
  await page.getByRole('button', { name: 'Avsluta', exact: true }).click();
  await page.getByRole('button', { name: 'Avsluta och spara' }).click(); await expect(page.getByRole('heading',{name:'Så påverkas nästa pass'})).toBeVisible(); await page.getByRole('button',{name:'Till planen',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Min träningsplan'})).toBeVisible();
  await page.getByRole('link', { name: 'Plan', exact: true }).click();
  await page.getByRole('radio', { name: 'Genomförda' }).click();
  await page.getByRole('button', { name: /^Pass 1 · / }).click();
  await page.getByRole('button', { name: 'Ta bort pass', exact: true }).click();
  await expect(page.getByRole('group', { name: 'Ta bort det här passet?' })).toBeVisible();
  const a11y = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  expect(a11y.violations.filter((v) => ['serious', 'critical'].includes(v.impact ?? ''))).toEqual([]);
  await page.getByRole('button', { name: 'Avbryt', exact: true }).click();
  await expect(page.getByRole('list', { name: 'Genomförda pass' }).locator(':scope > li')).toHaveCount(1);
  await page.getByRole('link', { name: 'Utveckling', exact: true }).click();
  await page.getByRole('button', { name: 'Ta bort pass', exact: true }).click();
  await context.setOffline(true);
  await page.getByRole('button', { name: 'Ja, ta bort passet' }).click();
  await expect(page.getByText('Inga avslutade pass ännu.')).toBeVisible();
  await expect(page.getByText('När du har genomfört pass visas din utveckling här.')).toBeVisible();
  await context.setOffline(false);
  await page.reload();
  await expect(page.getByText('Inga avslutade pass ännu.')).toBeVisible();
  await page.getByRole('link', { name: 'Plan', exact: true }).click();
  await page.getByRole('radio', { name: 'Kommande' }).click();
  await expect(page.getByRole('button', { name: /^Pass 2 · .*Nästa/ })).toBeVisible();
  const dimensions = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, width: document.documentElement.clientWidth }));
  expect(dimensions.scroll).toBeLessThanOrEqual(dimensions.width + 1);
});
