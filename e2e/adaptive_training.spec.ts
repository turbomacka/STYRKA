import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {mkdirSync} from 'node:fs';
import {signUp,onboard,uniqueEmail} from './helpers';
test('active workout: add, undo, delete, restore, offline reload and real replanning',async({page,context},info)=>{
  test.setTimeout(150000);
  await signUp(page,uniqueEmail('adaptive'));await onboard(page);
  await page.getByRole('button',{name:'Öppna passet',exact:true}).click();
  await page.getByRole('button',{name:'Starta passet',exact:true}).click();
  await expect(page.locator('.train-head h1')).toBeVisible();
  await expect(page.getByText('Uppvärmning och utförande',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('Visa uppvärmningsset')).toHaveCount(0);
  await page.getByRole('button',{name:'Lägg till övning',exact:true}).click();
  await page.getByRole('searchbox',{name:'Sök övning'}).fill('biceps');
  await page.getByRole('button',{name:'Bicepscurl',exact:true}).click();
  await expect(page.locator('.train-head h1')).toHaveText('Bicepscurl');
  const first=page.getByRole('listitem',{name:'Arbetsset 1',exact:true});
  await expect(first.getByRole('button',{name:/Vikt set 1:/})).not.toContainText('Välj vikt');
  await first.getByRole('button',{name:'Registrera set 1',exact:true}).click();
  await first.getByRole('button',{name:'Ångra registrering',exact:true}).click();
  await first.getByRole('button',{name:/Vikt set 1:/}).click();
  await first.getByLabel('Vikt (kg)',{exact:true}).fill('8');
  await expect(first.getByRole('status')).toContainText('Planen sparad');
  await first.getByRole('button',{name:'Stäng',exact:true}).click();
  await first.getByRole('button',{name:'Registrera set 1',exact:true}).click();
  await first.getByRole('button',{name:'Ta bort setet',exact:true}).click();
  await expect(first).toHaveCount(0);
  await page.locator('.toast').filter({hasText:'Setet borttaget'}).getByRole('button',{name:'Ångra',exact:true}).click();
  await expect(first.getByRole('button',{name:'Ångra registrering',exact:true})).toBeVisible();
  const dir='docs/evidence/adaptive-2026-10-22/'+info.project.name;mkdirSync(dir,{recursive:true});
  await page.screenshot({path:dir+'/added-exercise.png',fullPage:true});
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([]);
  // Windows WebKit cannot validate offline service worker reload; Android does.
  if(info.project.name!=='iphone-webkit'){
    await page.evaluate(async()=>{await navigator.serviceWorker.ready;});await context.setOffline(true);
  }
  await page.reload();
  await expect(first.getByRole('button',{name:/Vikt set 1:/})).toContainText('8');
  await expect(first.getByRole('button',{name:'Ångra registrering',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Avsluta',exact:true}).click();
  await page.getByRole('button',{name:'Avsluta och spara'}).click();
  await expect(page.getByRole('heading',{name:'Passet är sparat',exact:true})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Så påverkas kommande träning'})).toBeVisible();
  await expect(page.getByText('Dina extra arbetsset räknas in när kommande träningsdos planeras.')).toBeVisible();
  await page.screenshot({path:dir+'/extra-offline-finish.png',fullPage:true});
  await context.setOffline(false);
  await page.getByRole('button',{name:'Till planen',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Min träningsplan'})).toBeVisible();
  await page.getByRole('button',{name:'Visa genomfört pass'}).click();
  await page.locator('.plan-row-head').first().click();
  await page.getByRole('button',{name:'Korrigera set 1',exact:true}).click();
  const correction=page.getByRole('dialog',{name:'Korrigera registrering'});
  expect((await correction.getByLabel('Registrerad vikt (kg)').boundingBox())!.height).toBeGreaterThanOrEqual(44);
  await correction.getByLabel('Registrerad vikt (kg)').fill('10');
  await correction.getByRole('button',{name:'Spara korrigering'}).click();
  await expect(correction.getByRole('status')).toContainText('planen är uppdaterad');
  await page.screenshot({path:dir+'/history-correction.png',fullPage:true});
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([]);
  await correction.getByRole('button',{name:'Stäng',exact:true}).click();
  await expect(page.getByText('Korrigeringshistorik',{exact:true})).toBeVisible();
});
